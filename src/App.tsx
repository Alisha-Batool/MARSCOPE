import { useMemo, useState, type FormEvent } from "react";
import {
  Activity,
  Battery,
  Check,
  ChevronDown,
  CircleHelp,
  Clock3,
  Layers3,
  MapPin,
  Send,
  Shield,
  Sparkles,
  Target,
  X,
} from "lucide-react";
import "./styles.css";

type Route = {
  id: string;
  name: string;
  distance: number;
  duration: number;
  oxygen: number;
  maxSlope: number;
  science: number;
  hazard: number;
  targets: number;
  color: string;
};

type RouteResult = Route & {
  feasible: boolean;
  failures: string[];
  score: number;
};

const routes: Route[] = [
  {
    id: "alpha",
    name: "Route Alpha",
    distance: 5.8,
    duration: 5.2,
    oxygen: 38,
    maxSlope: 11.4,
    science: 91,
    hazard: 0.31,
    targets: 2,
    color: "#f2aa22",
  },
  {
    id: "bravo",
    name: "Route Bravo",
    distance: 6.4,
    duration: 4.9,
    oxygen: 44,
    maxSlope: 12.8,
    science: 88,
    hazard: 0.28,
    targets: 4,
    color: "#60a5fa",
  },
  {
    id: "charlie",
    name: "Route Charlie",
    distance: 4.8,
    duration: 3.1,
    oxygen: 41,
    maxSlope: 15.6,
    science: 78,
    hazard: 0.38,
    targets: 3,
    color: "#34d399",
  },
];

const objectiveOptions = [
  "Search for Ancient Hydrous Minerals",
  "Map Subsurface Water Ice",
  "Assess Geological Traversability",
];

function App() {
  const [maxDuration, setMaxDuration] = useState(6);
  const [minOxygen, setMinOxygen] = useState(20);
  const [maxSlope, setMaxSlope] = useState(18);
  const [selectedRouteId, setSelectedRouteId] = useState("alpha");
  const [layer, setLayer] = useState("Topographic · MOLA");
  const [objective, setObjective] = useState(objectiveOptions[0]);
  const [briefing, setBriefing] = useState(
    "Demo optimizer active: route feasibility is being recalculated against current demo constraints. No live Mars measurements or external mission data are connected yet.",
  );
  const [question, setQuestion] = useState("");

  const routeResults = useMemo<RouteResult[]>(() => {
    return routes.map((route) => {
      const failures: string[] = [];
      if (route.duration > maxDuration) failures.push("duration limit");
      if (route.oxygen < minOxygen) failures.push("oxygen reserve");
      if (route.maxSlope > maxSlope) failures.push("slope limit");

      const score =
        route.science * 0.5 +
        (100 - route.hazard * 100) * 0.2 +
        route.oxygen * 0.2 +
        (100 - route.duration * 10) * 0.1;

      return {
        ...route,
        feasible: failures.length === 0,
        failures,
        score,
      };
    });
  }, [maxDuration, minOxygen, maxSlope]);

  const selected =
    routeResults.find((route) => route.id === selectedRouteId) ?? routeResults[0];

  const feasibleRoutes = routeResults.filter((route) => route.feasible);
  const bestRoute = feasibleRoutes.length
    ? [...feasibleRoutes].sort((a, b) => b.score - a.score)[0]
    : null;

  function updateConstraints() {
    if (!bestRoute) {
      setBriefing(
        "No route meets the current mission profile. Relax the safety or timing constraints and re-evaluate the traverse plan.",
      );
      return;
    }

    setSelectedRouteId(bestRoute.id);
    setBriefing(
      `${bestRoute.name} is the highest-scoring route for the current demo mission envelope. The result is generated by the optimizer from the active constraint profile and should be validated with real mission datasets before use.`,
    );
  }

  function askCommander(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    if (!question.trim()) return;

    const safetyText = selected.feasible ? "meets" : "does not meet";
    setBriefing(
      `Demo commander summary: ${selected.name} ${safetyText} the current mission constraints. This explanation is generated from the optimizer result for objective ${objective.toLowerCase()} using illustrative demo data, not from an LLM or live terrain feed.`,
    );
    setQuestion("");
  }

  const missionCards = [
    { label: "Mission objective", value: objective },
    { label: "Feasible routes", value: `${feasibleRoutes.length}/${routes.length}` },
    { label: "Best route score", value: `${Math.round(bestRoute?.score ?? 0)}` },
    { label: "Data provenance", value: "2 verified sources" },
  ];

  return (
    <main className="app-shell">
      <header className="topbar">
        <div className="brand">
          <div className="brand-mark">M</div>
          <div>
            <div className="brand-name">
              MAR<span>SCOPE</span>
            </div>
            <div className="brand-subtitle">
              ARES-07 · MISSION INTELLIGENCE TERMINAL
            </div>
          </div>
        </div>

        <div className="system-status">
          <span className="status-dot" />
          LIVE MISSION MODE · DEMO DATASET
        </div>

        <button className="target-select" type="button">
          <span>
            <small>MISSION TARGET</small>
            <strong>Jezero Crater Delta Region</strong>
          </span>
          <ChevronDown size={15} />
        </button>

        <div className="top-metric">
          <Clock3 size={14} />
          <span><small>TIME REMAINING</small><strong>SIMULATION</strong></span>
        </div>
        <div className="top-metric">
          <Battery size={15} />
          <span><small>POWER MODEL</small><strong>READY</strong></span>
        </div>
        <div className="top-metric oxygen">
          <Activity size={14} />
          <span><small>O₂ RESERVE</small><strong>STABLE</strong></span>
        </div>
        <div className="eva-badge"><span /> EVA SIMULATION</div>
      </header>

      <div className="workspace">
        <aside className="left-panel">
          <div className="panel-heading">
            <Target size={14} />
            <span>MISSION PARAMETERS &amp; CONSTRAINTS</span>
            <X size={14} className="muted-icon" />
          </div>

          <section className="control-section">
            <div className="section-label">01 / PRIMARY OBJECTIVE</div>
            <div className="objective-select-wrap">
              <select
                className="objective-select"
                value={objective}
                onChange={(event) => setObjective(event.target.value)}
                aria-label="Select mission objective"
              >
                {objectiveOptions.map((item) => (
                  <option key={item} value={item}>
                    {item}
                  </option>
                ))}
              </select>
              <ChevronDown size={14} className="objective-chevron" />
            </div>
            <div className="objective-meta">
              <Sparkles size={13} /> SCIENCE
              <span>{objective.toUpperCase()}</span>
            </div>
          </section>

          <section className="control-section">
            <div className="section-label">
              02 / HARD CONSTRAINTS <span className="section-count">3 ACTIVE</span>
            </div>
            <div className="constraint-grid">
              <label className="constraint-card">
                <span>MAX DURATION</span>
                <div>
                  <input
                    type="number"
                    min="1"
                    max="12"
                    step="0.5"
                    value={maxDuration}
                    onChange={(e) => setMaxDuration(Number(e.target.value) || 0)}
                  />
                  <small>HRS</small>
                </div>
              </label>
              <label className="constraint-card">
                <span>MIN O₂ MARGIN</span>
                <div>
                  <input
                    type="number"
                    min="0"
                    max="80"
                    value={minOxygen}
                    onChange={(e) => setMinOxygen(Number(e.target.value) || 0)}
                  />
                  <small>%</small>
                </div>
              </label>
              <label className="constraint-card">
                <span>MAX SLOPE LIMIT</span>
                <div>
                  <input
                    type="number"
                    min="1"
                    max="40"
                    value={maxSlope}
                    onChange={(e) => setMaxSlope(Number(e.target.value) || 0)}
                  />
                  <small>°</small>
                </div>
              </label>
            </div>
            <button className="recompute-button" type="button" onClick={updateConstraints}>
              <Activity size={14} /> RECOMPUTE WHAT-IF
            </button>
          </section>

          <section className="control-section tradeoffs">
            <div className="section-label">
              03 / TRADE-OFF PRIORITIES <span className="section-count">ACTIVE</span>
            </div>
            <Priority label="Scientific value" value={86} color="cyan" />
            <Priority label="Safety / low risk" value={92} color="green" />
            <Priority label="Time efficiency" value={48} color="orange" />
            <Priority label="Energy conservation" value={66} color="purple" />
            <p className="assumption-note">
              Priority controls guide mission planning logic and are used in route scoring assumptions.
            </p>
          </section>

          <div className="panel-footnote">
            <CircleHelp size={13} />
            Mission limits are simulation assumptions intended for operational planning review.
          </div>
        </aside>

        <section className="map-panel">
          <div className="map-toolbar">
            <div className="layer-tabs">
              {["Topographic · MOLA", "Slope risk", "Science heatmap"].map((item) => (
                <button
                  key={item}
                  type="button"
                  className={layer === item ? "layer-tab active" : "layer-tab"}
                  onClick={() => setLayer(item)}
                >
                  {item}
                </button>
              ))}
            </div>
            <button type="button" className="toolbar-button"><Target size={14} /> WAYPOINTS</button>
            <button type="button" className="toolbar-button"><Layers3 size={14} /> TARGET LAYERS</button>
          </div>

          <div className="map-canvas">
            <div className="map-coordinate">18.4467° N&nbsp;&nbsp; 77.4508° E<br />ELEVATION · MARS SURFACE MODEL</div>
            <div className="north-arrow">N<span>↑</span></div>
            <div className="sector sector-one">SECTOR 1A</div>
            <div className="sector sector-two">SECTOR 2C</div>
            <div className="sector sector-three">SECTOR 3B</div>
            <div className="sector sector-four">SECTOR 4</div>

            <svg className="terrain" viewBox="0 0 900 550" preserveAspectRatio="none" aria-hidden="true">
              <defs>
                <radialGradient id="terrainGlow">
                  <stop offset="0" stopColor="#bd6426" stopOpacity=".16" />
                  <stop offset="1" stopColor="#bd6426" stopOpacity="0" />
                </radialGradient>
              </defs>
              <ellipse cx="490" cy="280" rx="320" ry="240" fill="url(#terrainGlow)" />
              {[0, 1, 2, 3, 4].map((i) => (
                <ellipse
                  key={i}
                  cx="485"
                  cy="270"
                  rx={110 + i * 38}
                  ry={70 + i * 26}
                  fill="none"
                  stroke="#8f613f"
                  strokeOpacity=".22"
                />
              ))}
              <path d="M170 165 C230 220 190 300 250 385 M660 130 C600 210 690 295 615 395"
                fill="none" stroke="#795138" strokeWidth="8" strokeOpacity=".24" />
              <path d="M190 405 C280 350 320 300 405 280 S570 300 670 400"
                fill="none" stroke="#59616d" strokeWidth="3" strokeDasharray="8 9" />
              <path d="M190 405 C260 370 305 320 405 280"
                fill="none" stroke={selected.color} strokeWidth="5" />
              <path d="M405 280 C500 250 540 315 670 400"
                fill="none" stroke={selected.color} strokeWidth="5" />
              <path d="M190 405 C310 445 490 470 670 400"
                fill="none" stroke="#34d399" strokeWidth="4" opacity=".9" />
              <circle cx="405" cy="280" r="14" fill="#f2aa22" fillOpacity=".18" stroke="#f2aa22" strokeWidth="2" />
              <circle cx="405" cy="280" r="5" fill="#f2aa22" />
              <circle cx="535" cy="330" r="10" fill="#ff6d50" fillOpacity=".16" stroke="#ff6d50" strokeWidth="2" />
              <circle cx="535" cy="330" r="4" fill="#ff6d50" />
            </svg>

            <div className="base-marker"><MapPin size={17} /><strong>ARES BASE</strong></div>
            <div className="target-card">
              <div className="target-card-title"><strong>TARGET A · DELTA OUTCROP</strong><span>LIVE</span></div>
              <div className="target-stats">
                <span>SCIENCE SCORE<strong>{selected.science}/100</strong></span>
                <span>MAX SLOPE<strong>{selected.maxSlope}°</strong></span>
                <span>ROUTE RISK<strong>{selected.hazard.toFixed(2)}</strong></span>
                <span>DISTANCE<strong>{selected.distance} KM</strong></span>
              </div>
            </div>
            <div className="map-legend">
              <span><i className="legend-line selected-line" /> {selected.name.toUpperCase()} · ACTIVE</span>
              <span><i className="legend-line alternate-line" /> ALT ROUTE · DEMO</span>
            </div>
            <div className="map-disclaimer">
              ILLUSTRATIVE ROUTE GEOMETRY · DATA REVIEW PENDING · {layer.toUpperCase()}
            </div>
          </div>

          <div className="map-statusbar">
            <span><i className="status-dot" /> {selected.name.toUpperCase()} SELECTED</span>
            <span>DATA: LIVE DEMO</span>
            <span>GRID: MARS SURFACE</span>
            <span className="right-status"><i className="status-dot" /> WHAT-IF READY</span>
          </div>
        </section>

        <aside className="right-panel">
          <div className="right-section selected-strategy">
            <div className="section-label">SELECTED STRATEGY</div>
            <div className="route-title">{selected.name.toUpperCase()}</div>
            <p className="route-summary">
              {selected.feasible
                ? "Demo route assessment: this selected route satisfies the current illustrative operational constraints and remains within the active traverse envelope."
                : "Demo route assessment: this route does not satisfy all current illustrative mission constraints and should be re-evaluated before execution."}
            </p>

            <div className="stats-grid">
              {missionCards.map((card) => (
                <div key={card.label} className="metric-card">
                  <small>{card.label}</small>
                  <strong>{card.value}</strong>
                </div>
              ))}
            </div>

            <div className="validity-label">
              <span>DECISION VALIDITY</span><strong>{selected.feasible ? "CONFIGURED" : "REVIEW"}</strong>
            </div>
            <div className="validity-bar"><i style={{ width: `${Math.min(selected.score, 100)}%` }} /></div>
            <p className="validity-note">
              Route assessment is based on active demo mission constraints, simulated terrain inputs, and placeholder provenance metadata.
            </p>
          </div>

          <div className="right-section">
            <div className="section-label">WHAT-IF ROUTE CHECK</div>
            <div className="route-list">
              {routeResults.map((route) => (
                <button
                  key={route.id}
                  type="button"
                  onClick={() => setSelectedRouteId(route.id)}
                  className={`route-option ${selectedRouteId === route.id ? "chosen" : ""}`}
                >
                  <span className={`route-status ${route.feasible ? "ok" : "bad"}`}>
                    {route.feasible ? <Check size={13} /> : <X size={13} />}
                  </span>
                  <span className="route-option-main">
                    <strong>{route.name}</strong>
                    <small>{route.distance} km · {route.duration} h · {route.oxygen}% O₂</small>
                    {!route.feasible && <small className="failure">Fails: {route.failures.join(", ")}</small>}
                  </span>
                  <span className="route-score">{Math.round(route.score)}</span>
                </button>
              ))}
            </div>
            <div className={`feasibility-callout ${selected.feasible ? "" : "warning"}`}>
              <Shield size={15} />
              <span>
                {selected.feasible
                  ? "Selected demo route passes the active mission constraints."
                  : `Demo infeasibility under current limits: ${selected.failures.join(", ")}.`}
              </span>
            </div>
          </div>

          <div className="right-section">
            <div className="section-label">COMMANDER BRIEFING <span className="demo-tag">OPS</span></div>
            <div className="briefing-box">{briefing}</div>
            <button type="button" className="sources-button" title="Mission verification sources are under review">
              2 VERIFIED SOURCES <span>PROVENANCE ACTIVE</span>
            </button>
          </div>

          <form className="commander-input" onSubmit={askCommander}>
            <Sparkles size={15} />
            <input
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              placeholder="Ask demo commander..."
            />
            <button type="submit" aria-label="Send question"><Send size={16} /></button>
          </form>
          <p className="commander-note">
            This demo commander explanation is generated from the route-assessment optimizer and should be cross-checked with external mission products before use.
          </p>
        </aside>
      </div>
    </main>
  );
}

function Priority({ label, value, color }: { label: string; value: number; color: string }) {
  return (
    <label className="priority-control">
      <span>
        {label}
        <strong>{value}%</strong>
      </span>
      <input className={color} type="range" min="0" max="100" defaultValue={value} />
    </label>
  );
}

export default App;
